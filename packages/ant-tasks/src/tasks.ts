/**
 * The "Sarcina Furnica" worksheet, a set of 24 tasks used in Moldovan
 * schools with the original program. Every task starts from the same world,
 * MAMATATA in row 2, and asks for the eight letters to be pushed into a
 * layout. The layouts were read from the worksheet's screenshots of the
 * original program.
 */

import type { GridObject, World } from "@repo/ant-runtime";

export interface Task {
	/** The task's number on the worksheet ("Sarcina №1"). */
	readonly number: number;
	/** Where every letter must end up. The ant may end anywhere. */
	readonly goal: readonly GridObject[];
}

/**
 * Draws a grid as rows of text, top to bottom: `.` is an empty cell and any
 * other character an object.
 */
function grid(rows: readonly string[]): GridObject[] {
	return rows.flatMap((row, y) =>
		[...row].flatMap((char, x) =>
			char === "." ? [] : [{ x: x + 1, y: y + 1, char }],
		),
	);
}

